def verify_answer(task, answer):
    if not isinstance(answer, str):
        return False
    answer = answer.strip()
    if task['kind'] == 'int':
        return bool(re.fullmatch(r'[+-]?\d+', answer)) and int(answer) == int(task['expected'])
    if task['kind'] == 'fraction':
        if not re.fullmatch(r'\d+\s*/\s*\d+', answer):
            return False
        try:
            return Fraction(answer.replace(' ', '')) == Fraction(task['expected'])
        except (ValueError, ZeroDivisionError):
            return False
    letters = re.sub(r'\s+', '', answer).upper().split(',')
    expected = task['expected'].split(',')
    if task['kind'] == 'set':
        return len(letters) == len(set(letters)) and set(letters) == set(expected)
    return letters == expected
